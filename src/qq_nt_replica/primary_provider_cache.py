_GUARDS = {'caller': 12283810, 'callback': 29360730, 'sdk': 0xBA156A}


def initialize(runtime, origin='caller'):
    if origin not in _OPERATIONS:
        raise InputError('provider cache origin must be caller, callback or sdk')
    failure = getattr(runtime, 'provider_cache_failure', None)
    if failure is not None:
        raise PrimarySemanticUnavailable('provider cache initialization previously stopped after state publication: ' + failure)
    memory, base = runtime.memory, runtime.image_base
    guard = base + 0x67519B0
    value = memory.load(guard, 4)
    if value & 1:
        return False
    try:
        memory.store(guard, value | 1, 4, source=f'{_GUARDS[origin]:X}.provider_cache_guard')
        for instruction, target, raw in _OPERATIONS[origin]:
            memory.write(base + target, bytes.fromhex(raw), source=f'{instruction:X}.provider_cache_constructor')
        values = (base + 0xBCD370,)
        vm = SimpleNamespace(cells=SimpleNamespace(value=lambda index: values[index]))
        result = runtime.invoke(vm, 0x3E680B4, (0,))
    except Exception as error:
        runtime.provider_cache_failure = repr(error)
        raise
    runtime.events.append(('provider_cache.constructed', origin, result))
    runtime.provider_cache_seed_pending = True
    return True
